-- Results of validation runs. Kept between runs so that data quality can be
-- followed over time (see queries/run_history.sql).

CREATE TABLE IF NOT EXISTS validation_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at    TIMESTAMP     NOT NULL,
    source        VARCHAR(1000) NOT NULL,
    tool_version  VARCHAR(20)   NOT NULL
);

CREATE TABLE IF NOT EXISTS checked_document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              BIGINT       NOT NULL REFERENCES validation_run (id),
    file_name           VARCHAR(500) NOT NULL,
    publication_number  VARCHAR(20),
    application_number  VARCHAR(30),
    receiving_office    CHAR(2),
    status              VARCHAR(10)  NOT NULL,
    CONSTRAINT ck_document_status CHECK (status IN ('VALID', 'WARNING', 'INVALID'))
);

CREATE TABLE IF NOT EXISTS finding (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT        NOT NULL REFERENCES checked_document (id),
    rule_id      VARCHAR(10)   NOT NULL,
    severity     VARCHAR(10)   NOT NULL,
    line_number  INT,
    message      VARCHAR(1000) NOT NULL,
    CONSTRAINT ck_finding_severity CHECK (severity IN ('ERROR', 'WARNING'))
);

CREATE INDEX IF NOT EXISTS ix_document_run ON checked_document (run_id);
CREATE INDEX IF NOT EXISTS ix_finding_document ON finding (document_id);
CREATE INDEX IF NOT EXISTS ix_finding_rule ON finding (rule_id);
